/**
 * Выполняется один раз при старте сервера.
 *
 * Схема и наполнение базы намеренно НЕ создаются здесь: на serverless-платформе
 * старт происходит при каждом холодном запуске, и миграция на каждом из них
 * была бы и медленной, и небезопасной при параллельных запусках.
 * Схема применяется отдельной командой `npm run db:migrate` перед деплоем.
 */
export async function register() {
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  if (!process.env.DATABASE_URL) {
    console.error(
      "[wms] Не задана переменная окружения DATABASE_URL — приложение не сможет подключиться к базе данных."
    );
  }
}
