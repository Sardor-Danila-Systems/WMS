/**
 * Локальная замена пакету `server-only`: даёт понятную ошибку, если серверный
 * модуль случайно попал в клиентский бандл, вместо невнятного «module not found».
 */
if (typeof window !== "undefined") {
  throw new Error(
    "Этот модуль работает только на сервере и не должен импортироваться в клиентском компоненте."
  );
}

